"""Build a local desktop bundle on the operating system that will run it."""

from __future__ import annotations

import importlib.util
import os
from pathlib import Path
import subprocess
import sys
import textwrap


ROOT = Path(__file__).resolve().parent.parent


def make_spec() -> Path:
    """Use PyInstaller's normal onedir graph and the standard Qt hooks.

    A spec is needed only to set macOS Info.plist values before signing.
    No PySide6 modules or Qt plugins are excluded by hand.
    """
    spec_dir = ROOT / "build" / "spec"
    spec_dir.mkdir(parents=True, exist_ok=True)
    spec = spec_dir / "MyBrush.spec"
    source = textwrap.dedent(
        f"""\
        # Generated by scripts/build.py. Edit that script, not this file.
        a = Analysis(
            [{str(ROOT / 'desktop_main.py')!r}],
            pathex=[{str(ROOT)!r}],
            binaries=[],
            datas=[],
            hiddenimports=[],
            hookspath=[],
            hooksconfig={{}},
            runtime_hooks=[],
            excludes=[],
            noarchive=False,
            optimize=0,
        )
        pyz = PYZ(a.pure)
        exe = EXE(
            pyz,
            a.scripts,
            [],
            exclude_binaries=True,
            name='MyBrush',
            debug=False,
            bootloader_ignore_signals=False,
            strip=False,
            upx=False,
            console=False,
            disable_windowed_traceback=False,
            argv_emulation=False,
            target_arch=None,
            codesign_identity=None,
            entitlements_file=None,
        )
        coll = COLLECT(
            exe,
            a.binaries,
            a.datas,
            strip=False,
            upx=False,
            name='MyBrush',
        )
        """
    )
    if sys.platform == "darwin":
        source += textwrap.dedent(
            """\
            app = BUNDLE(
                coll,
                name='MyBrush.app',
                bundle_identifier='dev.mybrush.desktop',
                info_plist={
                    'CFBundleDisplayName': 'My Brush',
                    'CFBundleName': 'My Brush',
                    'CFBundleShortVersionString': '0.1.0',
                    'CFBundleVersion': '1',
                    'LSMinimumSystemVersion': '14.0',
                    'NSHighResolutionCapable': True,
                },
            )
            """
        )
    spec.write_text(source, encoding="utf-8")
    return spec


def main() -> int:
    if sys.version_info < (3, 10):
        print("Python 3.10 이상이 필요합니다. Python 3.12를 권장합니다.", file=sys.stderr)
        return 1
    if sys.platform not in ("darwin", "win32"):
        print("macOS 또는 Windows에서 해당 운영체제용 앱을 빌드하세요.", file=sys.stderr)
        return 1
    if not (ROOT / "desktop_main.py").is_file():
        print("프로젝트의 desktop_main.py를 찾을 수 없습니다.", file=sys.stderr)
        return 1
    if any(importlib.util.find_spec(name) is None for name in ("PyInstaller", "PySide6")):
        print(
            "빌드 의존성을 먼저 설치하세요: "
            f'"{sys.executable}" -m pip install -r requirements-build.txt',
            file=sys.stderr,
        )
        return 1

    spec = make_spec()
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--distpath",
        str(ROOT / "dist"),
        "--workpath",
        str(ROOT / "build" / "pyinstaller"),
        str(spec),
    ]
    # The spec sets --windowed, --onedir, --name MyBrush and the entry point.
    environment = os.environ.copy()
    environment["PYINSTALLER_CONFIG_DIR"] = str(ROOT / "build" / "cache")
    subprocess.run(command, cwd=ROOT, env=environment, check=True)
    output = ROOT / "dist" / ("MyBrush.app" if sys.platform == "darwin" else "MyBrush")
    print(f"빌드 결과: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
